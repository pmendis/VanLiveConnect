#!/usr/bin/env python3
"""Generate TFT_eSPI smooth fonts (VLW format) as C arrays for the 3.5" HMI layout.

Source font: VanLiveConnect/data/PeugeotNewRegular.woff (the font of the web interface).
Output:      VanLiveConnect/HmiFonts.h

Requires: pip install freetype-py

VLW layout (all integers 32-bit big-endian):
  header : glyphCount, version(11), fontSize, 0, ascent, descent
  metrics: per glyph: unicode, height, width, xAdvance, dY (top above baseline), dX (left bearing), 0
  bitmaps: per glyph, width*height bytes of 8-bit alpha, in the same order as the metrics
"""
import os
import struct
import freetype

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "VanLiveConnect", "data", "PeugeotNewRegular.woff")
OUT = os.path.join(ROOT, "VanLiveConnect", "HmiFonts.h")

ASCII = "".join(chr(c) for c in range(0x21, 0x7F)) + "°"  # Printable ASCII (space is implicit) + degree sign

# name, pixel size, character set
FONTS = [
    ("hmiFontClock", 104, "0123456789:-"),
    ("hmiFontBig",    58, "0123456789.:-"),
    ("hmiFontNum",    40, "0123456789.:-RN"),
    ("hmiFontNumS",   32, "0123456789.:-"),
    ("hmiFontTitle",  26, ASCII),
    ("hmiFontText",   18, ASCII),
    ("hmiFontSmall",  14, ASCII),
    ("hmiFontTick",   11, "0123456789"),
]


def render(face, size, chars):
    face.set_pixel_sizes(0, size)
    glyphs = []
    for ch in sorted(set(chars)):
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        rows = []
        for y in range(h):
            rows.append(bytes(bm.buffer[y * bm.pitch: y * bm.pitch + w]))
        adv = (g.advance.x + 32) >> 6
        glyphs.append((ord(ch), h, w, adv, g.bitmap_top, g.bitmap_left, b"".join(rows)))
        assert w < 256 and h < 256 and adv < 256, (ch, w, h, adv)
    # Ascent from "d" / descent from "p" if present, else from the glyph set
    asc = max(g[4] for g in glyphs)
    desc = max(max(g[1] - g[4] for g in glyphs), 0)
    face.set_pixel_sizes(0, size)
    for ch, attr in (("d", "asc"), ("p", "desc")):
        if ch in chars:
            face.load_char(ch, freetype.FT_LOAD_RENDER)
            if attr == "asc":
                asc = face.glyph.bitmap_top
            else:
                desc = face.glyph.bitmap.rows - face.glyph.bitmap_top
    out = bytearray()
    out += struct.pack(">6i", len(glyphs), 11, size, 0, asc, desc)
    for (u, h, w, adv, top, left, _) in glyphs:
        out += struct.pack(">7i", u, h, w, adv, top, left, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


def main():
    face = freetype.Face(SRC)
    parts = ["// Generated by extras/Scripts/make_vlw_fonts.py from data/PeugeotNewRegular.woff - do not edit.\n",
             "// TFT_eSPI smooth fonts (VLW) for the 3.5\" HMI layout.\n\n",
             "#ifndef HmiFonts_h\n#define HmiFonts_h\n\n#include <pgmspace.h>\n\n"]
    total = 0
    for name, size, chars in FONTS:
        data = render(face, size, chars)
        total += len(data)
        parts.append(f"// {size} px, {len(set(chars))} glyphs, {len(data)} bytes\n")
        parts.append(f"const uint8_t {name}[] PROGMEM = {{\n")
        for i in range(0, len(data), 24):
            parts.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",\n")
        parts.append("};\n\n")
    parts.append("#endif // HmiFonts_h\n")
    open(OUT, "w", newline="\n").write("".join(parts))
    print(f"wrote {OUT}: {len(FONTS)} fonts, {total} bytes of font data")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Convert a black-on-white brand logo into the TFT boot logo (VanLiveConnect/LogoBitmap.h).

Usage: python make_logo.py <logo.png> [height_px] [preview.png]

The TFT background is dark, so the logo is converted to its "dark mode" form: the area around the emblem becomes
black, the emblem keeps its own black fill with its white lines, and the black lettering below the emblem turns
white. The result is a 4-bit grey (alpha) bitmap, two pixels per byte, drawn white-on-black by Display.ino.

LogoBitmap.h is git-ignored: brand logos are trademarks, keep them out of the public repository.

Requires: pip install pillow
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFilter, ImageOps

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "VanLiveConnect", "LogoBitmap.h")


def main():
    src = sys.argv[1]
    height = int(sys.argv[2]) if len(sys.argv) > 2 else 200
    preview = sys.argv[3] if len(sys.argv) > 3 else None

    img = Image.open(src)
    if img.mode in ("RGBA", "LA", "P"):
        img = img.convert("RGBA")
        bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
        img = Image.alpha_composite(bg, img)
    grey = img.convert("L")
    w, h = grey.size
    px = grey.load()

    # Rows with ink; the emblem is the first block of rows, the lettering the next one
    ink_rows = [any(px[x, y] < 128 for x in range(w)) for y in range(h)]
    first = ink_rows.index(True)
    split = first
    while split < h and ink_rows[split]:
        split += 1

    # Background around the emblem: flood fill over light pixels from the top-left corner, then grow it by two
    # pixels so the anti-aliased fringe of the emblem's outer black border disappears too
    binary = grey.point(lambda v: 255 if v > 128 else 0)
    ImageDraw.floodfill(binary, (0, 0), 128)
    bgmask = binary.point(lambda v: 255 if v == 128 else 0).filter(ImageFilter.MaxFilter(5))

    out = Image.new("L", (w, h), 0)
    op = out.load()
    bm = bgmask.load()
    for y in range(h):
        for x in range(w):
            v = px[x, y]
            if y >= split:
                op[x, y] = 255 - v          # Lettering: black on white -> white on black
            elif bm[x, y]:
                op[x, y] = 0                # Around the emblem
            else:
                op[x, y] = v                # Emblem: black fill stays black, white lines stay white

    bbox = out.getbbox()
    out = out.crop(bbox)
    scale = height / out.height
    out = out.resize((max(1, round(out.width * scale)), height), Image.LANCZOS)
    if out.width % 2:
        out = ImageOps.expand(out, border=(0, 0, 1, 0), fill=0)

    data = bytearray()
    op = out.load()
    for y in range(out.height):
        for x in range(0, out.width, 2):
            a = (op[x, y] + 8) // 17
            b = (op[x + 1, y] + 8) // 17
            data.append(min(a, 15) << 4 | min(b, 15))

    with open(OUT, "w", newline="\n") as f:
        f.write("// Generated by extras/Scripts/make_logo.py - do not edit. Git-ignored: keep brand logos out of the repo.\n")
        f.write("// TFT boot logo: 4-bit grey, two pixels per byte (high nibble first), white on black.\n\n")
        f.write("#ifndef LogoBitmap_h\n#define LogoBitmap_h\n\n#include <pgmspace.h>\n\n")
        f.write(f"#define LOGO_W {out.width}\n#define LOGO_H {out.height}\n\n")
        f.write("const uint8_t logoBitmap[] PROGMEM = {\n")
        for i in range(0, len(data), 24):
            f.write("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",\n")
        f.write("};\n\n#endif // LogoBitmap_h\n")
    print(f"wrote {OUT}: {out.width} x {out.height}, {len(data)} bytes")

    if preview:
        Image.merge("RGB", (out, out, out)).save(preview)
        print(f"preview {preview}")


if __name__ == "__main__":
    main()
